package main

import (
	"fmt"
	"strings"
)

// metadataSource identifies this plugin's reports to herdr, which keeps
// token state per source.
const metadataSource = "plugin:" + pluginID

// A report may mention at most 16 token keys.
const maxTokensPerReport = 16

// TokenPatches builds the workspace.report_metadata token maps that make
// herdr show exactly the selected tags: every configured tag is mentioned,
// set to its label when selected and null (cleared) otherwise, so a tag
// removed from the selection disappears. Selected names no longer in the
// config are ignored; their tokens are nobody's to clear.
func TokenPatches(cfg *Config, selected []string) []map[string]any {
	on := map[string]bool{}
	for _, name := range selected {
		on[name] = true
	}
	var patches []map[string]any
	for i, tag := range cfg.Tags {
		if i%maxTokensPerReport == 0 {
			patches = append(patches, map[string]any{})
		}
		var value any
		if on[tag.Name] {
			value = TagLabel(tag.Name)
		}
		patches[len(patches)-1][TokenName(tag.Name)] = value
	}
	return patches
}

// ReportTags pushes the selection for one workspace to herdr.
func ReportTags(sockPath, workspaceID string, cfg *Config, selected []string) error {
	for _, tokens := range TokenPatches(cfg, selected) {
		params := map[string]any{
			"workspace_id": workspaceID,
			"source":       metadataSource,
			"tokens":       tokens,
		}
		if _, err := apiRequest(sockPath, "workspace.report_metadata", params); err != nil {
			return fmt.Errorf("workspace %s: %w", workspaceID, err)
		}
	}
	return nil
}

// SidebarRowsTOML renders the [ui.sidebar.spaces] section for herdr's
// config.toml: the default rows plus one row holding every tag token in its
// color. Herdr styles tokens only in its own config, so this is where the
// colors from config.hcl have to end up.
func SidebarRowsTOML(cfg *Config) string {
	var b strings.Builder
	b.WriteString("# Generated by herdr-tags from its config.hcl. Paste into\n")
	b.WriteString("# ~/.config/herdr/config.toml (replacing any existing\n")
	b.WriteString("# [ui.sidebar.spaces] section), then run: herdr server reload-config\n")
	b.WriteString("[ui.sidebar.spaces]\n")
	b.WriteString("rows = [\n")
	b.WriteString("  [\"state_icon\", \"workspace\"],\n")
	b.WriteString("  [\"branch\", \"git_status\"],\n")
	b.WriteString("  [\n")
	for _, tag := range cfg.Tags {
		fmt.Fprintf(&b, "    { token = \"$%s\", fg = \"%s\" },\n", TokenName(tag.Name), tag.Color)
	}
	b.WriteString("  ],\n")
	b.WriteString("]\n")
	return b.String()
}
