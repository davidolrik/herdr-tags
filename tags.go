package main

import (
	"fmt"
	"strings"
)

// metadataSource identifies this plugin's reports to herdr, which keeps
// token state per source.
const metadataSource = "plugin:" + pluginID

// A report may mention at most 16 token keys.
const maxTokensPerReport = 16

// Herdr allows 16 sidebar rows; the default layout takes two of them.
const maxSidebarRows = 14

// Herdr draws " · " between two tokens on a sidebar row.
const tokenSeparatorWidth = 3

// tagLineCount is how many sidebar lines the tags can wrap onto: one each
// at worst, within what herdr has rows for once the note has its lines.
func tagLineCount(cfg *Config) int {
	return min(len(cfg.Tags), maxSidebarRows-cfg.NoteLines)
}

// PackLines wraps the selected tags, in config order, into sidebar lines of
// at most columns cells, counting herdr's separator between labels. A label
// wider than a line stands alone on it, and once the lines run out the rest
// share the last one. Selected names no longer in the config are ignored.
func PackLines(cfg *Config, selected []string, columns int) [][]string {
	on := map[string]bool{}
	for _, name := range selected {
		on[name] = true
	}
	var lines [][]string
	used := 0
	for _, tag := range cfg.Tags {
		if !on[tag.Name] {
			continue
		}
		width := len(TagLabel(tag.Name))
		fits := used+tokenSeparatorWidth+width <= columns || len(lines) == tagLineCount(cfg)
		if len(lines) == 0 || !fits {
			lines = append(lines, nil)
			used = -tokenSeparatorWidth
		}
		lines[len(lines)-1] = append(lines[len(lines)-1], tag.Name)
		used += tokenSeparatorWidth + width
	}
	return lines
}

// TokenPatches builds the workspace.report_metadata token maps that make
// herdr show exactly the selected tags, wrapped to columns cells: every
// token of every line is mentioned, set to its label where the tag sits and
// null (cleared) everywhere else, so a tag that moved line or left the
// selection disappears from where it was. Selected names no longer in the
// config are ignored; their tokens are nobody's to clear.
func TokenPatches(cfg *Config, selected []string, columns int) []map[string]any {
	lineOf := map[string]int{}
	for i, line := range PackLines(cfg, selected, columns) {
		for _, name := range line {
			lineOf[name] = i + 1
		}
	}
	var patches []map[string]any
	mentioned := 0
	for line := 1; line <= tagLineCount(cfg); line++ {
		for _, tag := range cfg.Tags {
			if mentioned%maxTokensPerReport == 0 {
				patches = append(patches, map[string]any{})
			}
			var value any
			if lineOf[tag.Name] == line {
				value = TagLabel(tag.Name)
			}
			patches[len(patches)-1][TokenName(line, tag.Name)] = value
			mentioned++
		}
	}
	return patches
}

// ReportTags pushes the selection for one workspace to herdr, wrapped to
// columns cells per sidebar line.
func ReportTags(sockPath, workspaceID string, cfg *Config, selected []string, columns int) error {
	for _, tokens := range TokenPatches(cfg, selected, columns) {
		if err := reportTokens(sockPath, workspaceID, tokens); err != nil {
			return err
		}
	}
	return nil
}

// reportTokens sends one token patch for a workspace to herdr.
func reportTokens(sockPath, workspaceID string, tokens map[string]any) error {
	params := map[string]any{
		"workspace_id": workspaceID,
		"source":       metadataSource,
		"tokens":       tokens,
	}
	if _, err := apiRequest(sockPath, "workspace.report_metadata", params); err != nil {
		return fmt.Errorf("workspace %s: %w", workspaceID, err)
	}
	return nil
}

// SidebarRowsTOML renders the [ui.sidebar.spaces] section for herdr's
// config.toml: the default rows plus one row per line the tags can wrap
// onto, each holding that line's token for every tag in its color, and then
// one row per line of the note. Herdr styles tokens only in its own config,
// so this is where the colors from config.hcl have to end up.
func SidebarRowsTOML(cfg *Config) string {
	var b strings.Builder
	b.WriteString("# Generated by herdr-tags from its config.hcl. Paste into\n")
	b.WriteString("# ~/.config/herdr/config.toml (replacing any existing\n")
	b.WriteString("# [ui.sidebar.spaces] section), then run: herdr server reload-config\n")
	b.WriteString("[ui.sidebar.spaces]\n")
	b.WriteString("rows = [\n")
	b.WriteString("  [\"state_icon\", \"workspace\"],\n")
	b.WriteString("  [\"branch\", \"git_status\"],\n")
	for line := 1; line <= tagLineCount(cfg); line++ {
		b.WriteString("  [\n")
		for _, tag := range cfg.Tags {
			fmt.Fprintf(&b, "    { token = \"$%s\", fg = \"%s\" },\n", TokenName(line, tag.Name), tag.Color)
		}
		b.WriteString("  ],\n")
	}
	for line := 1; line <= cfg.NoteLines; line++ {
		fmt.Fprintf(&b, "  [{ token = \"$%s\", fg = \"%s\" }],\n", NoteTokenName(line), cfg.NoteColor)
	}
	b.WriteString("]\n")
	return b.String()
}
